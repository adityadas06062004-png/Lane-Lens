"""Checks whether a clip behaves like footage from a real fixed traffic camera.

None of this can prove a video is genuine. Detecting generated video reliably is
an open problem. What it does is reject footage that breaks what a real fixed
camera produces (cuts, a moving viewpoint) and look for provenance markers that
some generators and editors leave behind. The strongest guarantee is still to take
footage straight from the camera feed and keep the file hash.
"""

import hashlib
import json
import math
import re
import shutil
import subprocess

import cv2
import numpy as np

OK, WARN, FAIL, SKIPPED = "ok", "warn", "fail", "skipped"
RANK = {OK: 0, SKIPPED: 0, WARN: 1, FAIL: 2}

AI_TOOL_WORDS = [
    "sora", "kling", "hailuo", "runwayml", "runway gen", "pika labs", "luma dream",
    "genmo", "midjourney", "stable video", "synthesia", "heygen", "veo 2", "veo 3",
    "ai generated", "ai-generated", "generated by ai", "text to video",
]
AI_SOURCE_TYPES = ("trainedalgorithmicmedia", "compositesynthetic", "algorithmicmedia")


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def scan_frames(path, max_samples=600):
    cap = cv2.VideoCapture(path)
    if not cap.isOpened():
        return None

    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT)) or 0
    stride = max(1, total // max_samples) if total else 1

    prev_hist = prev_gray = reference = window = None
    cuts = 0
    shifts = []
    sampled = 0
    index = -1

    while True:
        ok, frame = cap.read()
        if not ok:
            break
        index += 1
        if index % stride:
            continue

        h, w = frame.shape[:2]
        small = cv2.resize(frame, (320, max(int(h * 320 / w), 1)))
        gray = cv2.cvtColor(small, cv2.COLOR_BGR2GRAY)

        hist = cv2.calcHist([gray], [0], None, [32], [0, 256])
        cv2.normalize(hist, hist)

        if prev_hist is not None:
            similarity = cv2.compareHist(prev_hist, hist, cv2.HISTCMP_CORREL)
            change = float(np.mean(cv2.absdiff(prev_gray, gray)))
            if similarity < 0.5 or change > 45:
                cuts += 1
        prev_hist, prev_gray = hist, gray

        current = np.float32(gray)
        if reference is None:
            reference = current
            window = cv2.createHanningWindow((current.shape[1], current.shape[0]), cv2.CV_32F)
        else:
            (dx, dy), _ = cv2.phaseCorrelate(reference, current, window)
            shifts.append(math.hypot(dx, dy) / current.shape[1])
        sampled += 1

    cap.release()
    return {
        "frames_sampled": sampled,
        "cuts": cuts,
        "median_shift": float(np.median(shifts)) if shifts else 0.0,
        "p90_shift": float(np.percentile(shifts, 90)) if shifts else 0.0,
    }


def read_metadata(path):
    if shutil.which("ffprobe") is None:
        return None
    done = subprocess.run(
        ["ffprobe", "-v", "quiet", "-print_format", "json",
         "-show_format", "-show_streams", path],
        capture_output=True, text=True,
    )
    if done.returncode != 0:
        return None
    try:
        return json.loads(done.stdout)
    except ValueError:
        return None


def metadata_text(info):
    values = []
    pools = [info.get("format", {}).get("tags", {})]
    pools += [s.get("tags", {}) for s in info.get("streams", [])]
    for tags in pools:
        values += [str(v) for v in tags.values()]
    return " ".join(values).lower()


def content_credentials(path):
    """Reads C2PA content credentials when the free c2patool is installed."""
    if shutil.which("c2patool") is None:
        return None
    done = subprocess.run(["c2patool", path], capture_output=True, text=True)
    text = (done.stdout + done.stderr).lower()
    return {
        "present": "manifest" in text and "no claim" not in text,
        "ai": any(word in text for word in AI_SOURCE_TYPES),
    }


def check_source(path):
    checks = []

    def add(name, status, detail):
        checks.append({"name": name, "status": status, "detail": detail})

    scan = scan_frames(path)
    if scan is None or scan["frames_sampled"] < 10:
        add("Readable clip", FAIL, "The video could not be read or is too short to check.")
        return finish(path, checks)

    if scan["cuts"] == 0:
        add("Continuous footage", OK, "No scene cuts found. Real camera feeds do not cut.")
    else:
        add("Continuous footage", FAIL,
            f"{scan['cuts']} scene cut(s) found. This looks edited or assembled, not a live feed.")

    if scan["median_shift"] <= 0.01 and scan["p90_shift"] <= 0.03:
        add("Fixed camera", OK, "The background stays in place, as expected from a mounted camera.")
    else:
        add("Fixed camera", FAIL,
            "The viewpoint moves. The rules need a fixed camera, and handheld, dashcam or "
            "generated footage usually fails this test.")

    info = read_metadata(path)
    if info is None:
        add("File metadata", SKIPPED, "ffprobe is not available, so metadata was not read.")
    else:
        text = metadata_text(info)
        hits = [w for w in AI_TOOL_WORDS if re.search(r"\b" + re.escape(w) + r"\b", text)]
        if hits:
            add("File metadata", WARN, "Mentions a video generation tool: " + ", ".join(hits))
        else:
            add("File metadata", OK,
                "No generation tool named. Metadata is easy to strip, so this proves little.")

    creds = content_credentials(path)
    if creds is None:
        add("Content credentials", SKIPPED, "c2patool is not installed, so C2PA was not checked.")
    elif creds["ai"]:
        add("Content credentials", FAIL, "Signed content credentials say this media is AI generated.")
    elif creds["present"]:
        add("Content credentials", OK, "Content credentials are present and do not mark it as generated.")
    else:
        add("Content credentials", OK, "No content credentials found, which is normal for camera files.")

    return finish(path, checks)


def finish(path, checks):
    worst = max((RANK[c["status"]] for c in checks), default=0)
    verdict = ["pass", "review", "block"][worst]
    return {"verdict": verdict, "checks": checks, "sha256": sha256_file(path)}
